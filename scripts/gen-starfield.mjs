/**
 * Generates the full-bleed star field behind the page.
 *
 * "The sky is thin and dreamy" — dust only, no arcs, no bright stars, so it
 * never competes with the halo constellation. Deterministic seed keeps the
 * field identical across builds.
 *
 * Re-run with: node scripts/gen-starfield.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const W = 1440
const H = 900
const COUNT = 96

const GOLD = '#E6BA4E'
const FAINT = '#8A7C67'
const PALE = '#D0C4AB'

let seed = 719003
const rnd = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296
  return seed / 4294967296
}
const n = (v) => Math.round(v * 100) / 100

const rows = []
for (let i = 0; i < COUNT; i++) {
  const x = rnd() * W
  const y = rnd() * H
  // thin the field toward the optical centre so the copy stays clean
  const dx = (x - W / 2) / (W / 2)
  const dy = (y - H / 2) / (H / 2)
  const centreness = 1 - Math.min(1, Math.hypot(dx, dy))
  if (rnd() < centreness * 0.72) continue

  const d = 1.1 + rnd() * 1.4
  const op = 0.1 + rnd() * 0.34
  const t = rnd()
  const fill = t > 0.78 ? GOLD : t > 0.5 ? PALE : FAINT
  rows.push(
    `      <circle cx="${n(x)}" cy="${n(y)}" r="${n(d / 2)}" fill="${fill}" opacity="${n(op)}" />`,
  )
}

const tsx = `// AUTO-GENERATED by scripts/gen-starfield.mjs — do not edit by hand.
// Thin dust field behind the page. No arcs, no bright stars — the halo
// constellation is the only thing that reads as a constellation.

export default function StarField({ className }: { className?: string }) {
  return (
    <svg
      className={className}
      viewBox="0 0 ${W} ${H}"
      preserveAspectRatio="xMidYMid slice"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
    >
${rows.join('\n')}
    </svg>
  )
}
`

const __dirname = dirname(fileURLToPath(import.meta.url))
writeFileSync(join(__dirname, '..', 'components', 'StarField.tsx'), tsx)
console.log(`wrote components/StarField.tsx (${rows.length} stars)`)
